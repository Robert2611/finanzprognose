"""Generate COVERAGE.md and TEST_REPORT.md from results.json (written by the suite's recorder).

Usage:  python -m tests.contract.helpers.report
Failure classifications live in failure_notes.json (hand-written: clause, contract says, what happened, class).
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

from tests.contract.helpers.clauses import known_ids

HERE = Path(__file__).resolve().parents[1]
LAYERS = ["data", "backend", "api", "backup", "frontend", "e2e"]
ORDER = {"passed": 0, "failed": 1, "skipped": 2, "xfailed": 3, "xpassed": 4}


def layer_of(nodeid: str) -> str:
    parts = nodeid.split("/")
    return parts[2] if len(parts) > 3 and parts[2] in LAYERS else "other"


def short(nodeid: str) -> str:
    return nodeid.split("::", 1)[1].replace("[chromium]", "") if "::" in nodeid else nodeid


def main():
    results = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
    notes = json.loads((HERE / "failure_notes.json").read_text(encoding="utf-8")) if (HERE / "failure_notes.json").exists() else {}
    known = known_ids()

    # ---- totals per layer
    per_layer = defaultdict(Counter)
    for r in results:
        per_layer[layer_of(r["nodeid"])][r["outcome"]] += 1
    total = Counter()
    for c in per_layer.values():
        total.update(c)

    # ---- clause -> tests
    by_clause = defaultdict(list)
    for r in results:
        for cid in r["clauses"]:
            by_clause[cid].append(r)

    def status(rs):
        outs = Counter(r["outcome"] for r in rs)
        if outs["failed"]:
            return "FAILED" if not outs["passed"] else "PARTIAL (some failing)"
        if outs["passed"]:
            return "passed" if not outs["skipped"] else "passed (some skipped)"
        return "skipped"

    # ---- COVERAGE.md
    lines = ["# Clause coverage", "", "Generated by `python -m tests.contract.helpers.report` from `results.json`.", "",
             "Status per clause: `passed`, `FAILED`, `PARTIAL` (some tests of the clause fail), `skipped` (only skipped tests).", ""]
    section = None
    uncovered = []
    for cid, sec in known.items():
        if sec != section:
            section = sec
            lines += ["", f"## {sec}", "", "| Clause | Status | Tests |", "|---|---|---|"]
        rs = by_clause.get(cid, [])
        if not rs:
            uncovered.append(cid)
            lines.append(f"| {cid} | **UNCOVERED** | - |")
            continue
        names = sorted({short(r["nodeid"]) for r in rs})
        shown = ", ".join(f"`{n}`" for n in names[:4]) + (f" (+{len(names) - 4} more)" if len(names) > 4 else "")
        lines.append(f"| {cid} | {status(rs)} | {len(names)}: {shown} |")
    lines += ["", "## Uncovered clauses", ""]
    lines += [f"- {c}" for c in uncovered] if uncovered else ["None: every clause in `contracts/TRACEABILITY.md` has at least one test (possibly a skip stub)."]
    extra = sorted(set(by_clause) - set(known))
    if extra:
        lines += ["", "## Unknown IDs referenced by tests", ""] + [f"- {c}" for c in extra]
    (HERE / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---- TEST_REPORT.md
    rep = ["# Contract test report", "",
           "Generated by `python -m tests.contract.helpers.report` from `results.json`. Nothing was fixed and no test was adjusted to make it pass.", "",
           "## Totals", "", "| Layer | Passed | Failed | Skipped | Total |", "|---|---|---|---|---|"]
    for layer in LAYERS:
        c = per_layer.get(layer, Counter())
        rep.append(f"| {layer} | {c['passed']} | {c['failed']} | {c['skipped']} | {sum(c.values())} |")
    rep.append(f"| **all** | **{total['passed']}** | **{total['failed']}** | **{total['skipped']}** | **{sum(total.values())}** |")
    clause_status = Counter(status(by_clause[c]) for c in known if c in by_clause)
    rep += ["", f"Clauses: {len(known)} in TRACEABILITY.md; {len(known) - len(uncovered)} have at least one test; "
                f"{clause_status['passed']} fully passing, {clause_status['passed (some skipped)']} passing with skipped parts, "
                f"{clause_status['FAILED'] + clause_status['PARTIAL (some failing)']} with failing tests, {clause_status['skipped']} only skipped."]

    failures = [r for r in results if r["outcome"] == "failed"]
    rep += ["", f"## Failures ({len(failures)})", ""]
    if not failures:
        rep.append("None.")
    for r in failures:
        n = notes.get(short(r["nodeid"]), {})
        rep += [f"### {', '.join(r['clauses'])}: `{short(r['nodeid'])}`", "",
                f"- **Contract says:** {n.get('contract', '(see clause)')}",
                f"- **What happened:** {n.get('happened') or r['reason'][:400]}",
                f"- **Classification:** {n.get('class', 'UNCLASSIFIED')}"]
        if n.get("note"):
            rep.append(f"- **Note:** {n['note']}")
        rep.append("")

    skipped = [r for r in results if r["outcome"] == "skipped"]
    rep += [f"## Skipped ({len(skipped)})", "", "| Test | Clauses | Reason |", "|---|---|---|"]
    for r in sorted(skipped, key=lambda r: r["nodeid"]):
        rep.append(f"| `{short(r['nodeid'])}` | {', '.join(r['clauses'])} | {r['reason'].replace('|', '/')[:180]} |")
    (HERE / "TEST_REPORT.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print(f"wrote COVERAGE.md and TEST_REPORT.md: {dict(total)}; uncovered clauses: {len(uncovered)}")


if __name__ == "__main__":
    main()
